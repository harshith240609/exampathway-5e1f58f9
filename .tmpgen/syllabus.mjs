const q = (s) => "'" + s.replace(/'/g, "''") + "'";
const chapterRows = [];
const topicRows = [];
for (const [subj, chapters] of Object.entries(S)) {
  let ci = 0;
  for (const [chap, topics] of Object.entries(chapters)) {
    ci += 1;
    chapterRows.push(`(${q(subj)},${q(chap)},${ci})`);
    topics.forEach((t, ti) =>
      topicRows.push(`(${q(subj)},${q(chap)},${q(t)},${ti + 1})`),
    );
  }
}
console.log(`WITH ch(subject_name, chapter_name, ord) AS (VALUES
${chapterRows.join(",\n")}
)
INSERT INTO public.chapters (subject_id, name, sort_order)
SELECT s.id, ch.chapter_name, ch.ord
FROM ch JOIN public.subjects s ON s.name = ch.subject_name
WHERE NOT EXISTS (SELECT 1 FROM public.chapters c WHERE c.subject_id = s.id AND c.name = ch.chapter_name);

WITH tp(subject_name, chapter_name, topic_name, ord) AS (VALUES
${topicRows.join(",\n")}
)
INSERT INTO public.topics (chapter_id, name, sort_order)
SELECT c.id, tp.topic_name, tp.ord
FROM tp
JOIN public.subjects s ON s.name = tp.subject_name
JOIN public.chapters c ON c.subject_id = s.id AND c.name = tp.chapter_name
WHERE NOT EXISTS (SELECT 1 FROM public.topics t WHERE t.chapter_id = c.id AND t.name = tp.topic_name);`);
